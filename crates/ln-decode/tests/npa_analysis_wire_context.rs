#[test]
fn synthetic_claims_and_derivations_render_closed_tokens() {
    let p = pipeline(&wrap(CONTEXT_BODY));
    let live = build_context_records(&p.analysis.layout, &p.mapping);
    let anchor = live
        .iter()
        .find_map(|record| match record {
            ContextRecord::Result(result) => result
                .anchors
                .iter()
                .find(|anchor| anchor.is_bound())
                .cloned(),
            ContextRecord::Run(_) => None,
        })
        .expect("the framed fixture emits at least one bound anchor");

    let result = ContextRecord::Result(ContextResultRecord {
        reference: "ctx:0".to_string(),
        request_ref: "req-claim".to_string(),
        request_kind: ContextRequestKind::OpenSeriesHead,
        view: Some("covering"),
        status: ContextStatus::Resolved,
        claims: vec![ContextClaimRecord {
            field: "series_head".to_string(),
            claim_status: ContextClaimStatus::Explicit,
            derivation: DerivationSource::ExplicitMember,
            source_node_ref: "node-1".to_string(),
            anchor: anchor.clone(),
        }],
        derivations: vec![ContextDerivationRecord {
            from: "node-1".to_string(),
            to: "node-2".to_string(),
            relation: DerivationRelation::DerivedFrom,
            status: StructureEdgeStatus::Accepted,
            anchor: anchor.clone(),
        }],
        diagnostics: vec![ContextDiagnostic::OpenSeriesWithoutHead],
        anchors: vec![anchor],
    });
    let text = render_with_context(&p, &[result]);
    let line = context_lines(&text)
        .into_iter()
        .find(|line| json_string_value(line, "kind").as_deref() == Some("result"))
        .expect("the synthetic result rendered");
    assert!(line.contains("\"claim_status\":\"explicit\""));
    assert!(line.contains("\"derivation\":\"explicit_member\""));
    assert!(line.contains("\"source_node_ref\":\"node-1\""));
    assert!(line.contains("\"relation\":\"derived_from\""));
    assert!(line.contains("\"from\":\"node-1\""));
    assert!(line.contains("\"to\":\"node-2\""));
    assert!(line.contains("\"open_series_without_head\""));
    // A resolved, non-refused synthetic result keeps the envelope complete.
    let summary = inspect_npa_analysis_wire(&text).expect("the synthetic envelope inspects");
    assert_eq!(summary.completion, "complete");
    assert_eq!(summary.completion_basis, BASIS_COMPLETE);
}

