// --------------------------------------------------- completion honesty #

#[test]
fn non_resolved_context_forces_context_incomplete() {
    let p = pipeline(&wrap(CONTEXT_BODY));
    let contexts = build_context_records(&p.analysis.layout, &p.mapping);
    // No context anchor is refused under the pinned parent, so the honesty
    // signal comes from the non-resolved this-ref requisites status, not from a
    // refusal.
    let text = render_with_context(&p, &contexts);
    let summary = inspect_npa_analysis_wire(&text).expect("honest partial inspects");
    assert_eq!(summary.completion, "incomplete");
    assert_eq!(summary.completion_basis, BASIS_CONTEXT_INCOMPLETE);
    assert!(
        summary
            .incomplete_reasons
            .contains(&BASIS_CONTEXT_INCOMPLETE.to_string()),
        "the basis token is a reason"
    );
    assert!(
        summary
            .incomplete_reasons
            .iter()
            .any(|reason| reason.starts_with("context_") && reason != BASIS_CONTEXT_INCOMPLETE),
        "at least one closed non-resolved status reason is present"
    );
}

#[test]
fn promoting_context_incomplete_to_complete_is_refused() {
    let p = pipeline(&wrap(CONTEXT_BODY));
    let contexts = build_context_records(&p.analysis.layout, &p.mapping);
    let text = render_with_context(&p, &contexts);
    let promoted = text.replace(
        "\"completion\":\"incomplete\"",
        "\"completion\":\"complete\"",
    );
    assert_ne!(promoted, text, "the mutation changed the footer");
    assert_eq!(
        inspect_npa_analysis_wire(&promoted)
            .expect_err("a context partial cannot be presented as complete")
            .kind(),
        AnalysisWireErrorKind::CompletionMarkerInvalid
    );
}

#[test]
fn refused_context_anchor_forces_refused_record_not_context_incomplete() {
    let p = pipeline(&wrap(CONTEXT_BODY));
    let contexts = build_context_records(&p.analysis.layout, &unpinned_mapping(&p));
    // The unpinned parent refuses every anchor, so the refusal outranks the
    // non-resolved context status (§8B.3 rule 3).
    let text = render_with_context(&p, &contexts);
    let summary = inspect_npa_analysis_wire(&text).expect("a refused context anchor inspects");
    assert_eq!(summary.completion, "incomplete");
    assert_eq!(summary.completion_basis, "refused_record");
    assert_eq!(
        summary.incomplete_reasons,
        vec!["refused_record".to_string()]
    );
}

#[test]
fn limit_status_is_never_promoted() {
    let p = pipeline(&wrap(TYPED_BODY));
    let limit = ContextRecord::Result(ContextResultRecord {
        reference: "ctx:0".to_string(),
        request_ref: "req-limit".to_string(),
        request_kind: ContextRequestKind::ExplicitAnchorLookup,
        view: Some("covering"),
        status: ContextStatus::Limit,
        claims: Vec::new(),
        derivations: Vec::new(),
        diagnostics: vec![ContextDiagnostic::ContextQueryLimitReached],
        anchors: Vec::new(),
    });
    let text = render_with_context(&p, &[limit]);
    let summary = inspect_npa_analysis_wire(&text).expect("a limit outcome inspects");
    assert_eq!(summary.completion, "incomplete");
    assert_eq!(summary.completion_basis, BASIS_CONTEXT_INCOMPLETE);
    assert!(
        summary
            .incomplete_reasons
            .contains(&"context_limit".to_string()),
        "a limit status is surfaced as a closed reason"
    );
    let run = context_lines(&text)
        .into_iter()
        .find(|line| json_string_value(line, "kind").as_deref() == Some("result"))
        .expect("the synthetic limit result rendered");
    assert!(run.contains("\"status\":\"limit\""));
}

