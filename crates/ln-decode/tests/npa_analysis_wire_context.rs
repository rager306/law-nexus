fn wrap(body: &str) -> String {
    format!(
        "<w:wordDocument xmlns:w=\"http://schemas.microsoft.com/office/word/2003/wordml\"><w:body>{body}</w:body></w:wordDocument>"
    )
}

struct Pipeline {
    analysis: DocumentAnalysis,
    projection: ReaderProjection,
    index: ReaderRecordIndex,
    mapping: SourceMapping,
}

/// Runs the real pipeline: capture -> projection -> document analysis, with a
/// mapping that pins every substrate fragment.
fn pipeline(xml: &str) -> Pipeline {
    let package = capture(xml.as_bytes(), &Limits::default()).expect("fixture must capture");
    let index = ReaderRecordIndex::new(package.records()).expect("substrate index");
    let projection = build_projection(package.records()).expect("projection must build");
    let identity = SourceIdentity::try_new(
        package.manifest().source.sha256.clone(),
        package.manifest().source.bytes,
        "law-nexus/source-package-model/v1".to_string(),
        package.footer().records_seal_hash.clone(),
        package.footer().manifest_hash.clone(),
    )
    .expect("manifest identity must be well formed");
    let version = DocumentVersionRef::try_new(
        "doc-version-1".to_string(),
        "rev-1".to_string(),
        "reader_wordml_profile/v1".to_string(),
    )
    .expect("version triple must be well formed");
    let mut mapping = SourceMapping::new(identity.clone(), version);
    for text in index.texts() {
        mapping
            .pin_fragment(
                FragmentRef::from(text.id.as_str()),
                text.value.clone(),
                &identity,
            )
            .expect("every substrate fragment must pin");
    }
    let analysis = analyze_document(&projection, &index, &mapping).expect("analysis must build");
    Pipeline {
        analysis,
        projection,
        index,
        mapping,
    }
}

/// The same layout with an unpinned mapping: every context anchor is refused.
fn unpinned_mapping(p: &Pipeline) -> SourceMapping {
    SourceMapping::new(p.mapping.envelope().clone(), p.mapping.version().clone())
}

fn envelope_request(p: &Pipeline) -> AnalysisEnvelopeRequest<'_> {
    AnalysisEnvelopeRequest {
        analysis: &p.analysis,
        projection: &p.projection,
        index: &p.index,
        mapping: &p.mapping,
        limits: AnalysisLimits::default(),
        scope: AnalysisScope::Bounded,
    }
}

fn render_with_context(p: &Pipeline, contexts: &[ContextRecord]) -> String {
    let request = envelope_request(p);
    render_npa_analysis_with_context(&request, contexts)
        .expect("a valid context envelope must render")
}

fn render_s02(p: &Pipeline) -> String {
    let request = envelope_request(p);
    render_npa_analysis(&request).expect("a valid S02 envelope must render")
}

fn lines(text: &str) -> Vec<&str> {
    assert!(text.ends_with('\n'), "envelope ends with one trailing LF");
    let body = &text[..text.len() - 1];
    body.split('\n').collect()
}

fn json_string_value(line: &str, key: &str) -> Option<String> {
    let needle = format!("\"{key}\":\"");
    let start = line.find(&needle)? + needle.len();
    let rest = &line[start..];
    let end = rest.find('"')?;
    Some(rest[..end].to_string())
}

fn context_lines(text: &str) -> Vec<&str> {
    lines(text)
        .into_iter()
        .filter(|line| json_string_value(line, "family").as_deref() == Some(FAMILY_CONTEXT))
        .collect()
}

const TYPED_BODY: &str = "<w:p><w:r><w:t>Федеральный закон от 01.01.2020 N 1-ФЗ</w:t></w:r></w:p>";

// A heading designation frame plus two act-requisites paragraphs: the heading
// carries a this-ref surface but no letterhead is present, so a
// current-document-requisites request is emitted and stays non-resolved
// (`unavailable`); the bare `от ДАТА N` continuation tail exercises a resolved
// open-series head.
const CONTEXT_BODY: &str =
    "<w:p><w:r><w:t>Статья 1. Настоящего Федерального закона</w:t></w:r></w:p>\
     <w:p><w:r><w:t>Федерального закона от 01.01.2020 N 1-ФЗ,</w:t></w:r></w:p>\
     <w:p><w:r><w:t>от 02.02.2021 N 2-ФЗ</w:t></w:r></w:p>";

// ------------------------------------------------------------- opt-in #

#[test]
fn empty_context_is_byte_identical_to_s02() {
    let p = pipeline(&wrap(TYPED_BODY));
    let s02 = render_s02(&p);
    let with_empty = render_with_context(&p, &[]);
    assert_eq!(
        s02, with_empty,
        "an empty context slice must not shift a single byte of the S02 envelope"
    );
    assert!(
        !with_empty.contains("\"family\":\"context\""),
        "no context line with an empty slice"
    );
    assert!(
        !with_empty.contains("\"contexts\":"),
        "no contexts key with an empty slice"
    );
    let summary = inspect_npa_analysis_wire(&with_empty).expect("the S02 envelope must inspect");
    assert_eq!(summary.completion, "complete");
    assert_eq!(summary.completion_basis, BASIS_COMPLETE);
    assert_eq!(summary.families.get(FAMILY_CONTEXT), None);
}

#[test]
fn seventh_family_is_admitted_but_not_emitted_by_s02() {
    assert_eq!(FAMILIES.len(), 7);
    assert!(FAMILIES.contains(&FAMILY_CONTEXT));
    assert_eq!(SCHEMA_CONTEXT, "law-nexus/npa-analysis-context/v1");
}

// ------------------------------------------------------- context family #

#[test]
fn context_lines_follow_diagnostics_and_footer_gains_counts() {
    let p = pipeline(&wrap(CONTEXT_BODY));
    let contexts = build_context_records(&p.analysis.layout, &p.mapping);
    assert!(
        !contexts.is_empty(),
        "a framed fixture must emit at least one context line"
    );
    let text = render_with_context(&p, &contexts);
    let all = lines(&text);
    let last = all.len() - 1;

    let context_count = contexts.len();
    assert_eq!(
        context_lines(&text).len(),
        context_count,
        "every context record renders exactly one line"
    );

    // Context lines are the last interior lines; the line before them is not a
    // context line (diagnostics, if any, precede).
    let start = last - context_count;
    for line in &all[start..last] {
        assert_eq!(
            json_string_value(line, "family").as_deref(),
            Some(FAMILY_CONTEXT)
        );
    }
    if start > 2 {
        assert_ne!(
            json_string_value(all[start - 1], "family").as_deref(),
            Some(FAMILY_CONTEXT),
            "context lines are contiguous and come last"
        );
    }

    // Footer counts gain `contexts`; the six S02 counts are unchanged.
    let footer = all[last];
    assert!(
        footer.contains(&format!("\"contexts\":{context_count}")),
        "the footer counts the emitted context records"
    );
    for key in [
        "classifications",
        "diagnostics",
        "documents",
        "fragments",
        "members",
        "records",
        "relations",
    ] {
        assert!(
            footer.contains(&format!("\"{key}\":")),
            "the six S02 counts stay present ({key})"
        );
    }

    let summary = inspect_npa_analysis_wire(&text).expect("the context envelope must inspect");
    assert_eq!(
        summary.families.get(FAMILY_CONTEXT).copied(),
        Some(context_count as u64)
    );
    assert_eq!(summary.families.values().sum::<u64>(), summary.records);

    // No inline decoded corpus text anywhere in the envelope.
    for forbidden in [
        "\"text\":",
        "\"source_utf8\":",
        "\"inline_text\":",
        "\"decoded_text\":",
        "\"segment_text\":",
    ] {
        assert!(
            !text.contains(forbidden),
            "the context envelope must not carry inline decoded text ({forbidden})"
        );
    }
}

#[test]
fn context_result_and_run_lines_carry_closed_tokens() {
    let p = pipeline(&wrap(CONTEXT_BODY));
    let contexts = build_context_records(&p.analysis.layout, &p.mapping);
    let text = render_with_context(&p, &contexts);

    let mut results = 0usize;
    let mut runs = 0usize;
    for line in context_lines(&text) {
        assert_eq!(
            json_string_value(line, "schema").as_deref(),
            Some(SCHEMA_CONTEXT)
        );
        match json_string_value(line, "kind").as_deref() {
            Some("result") => {
                results += 1;
                let request_kind = json_string_value(line, "request_kind").expect("request_kind");
                assert!(
                    [
                        "ancestor_path",
                        "adjacent_blocks",
                        "open_series_head",
                        "scoped_alias",
                        "current_document_requisites",
                        "explicit_anchor_lookup",
                    ]
                    .contains(&request_kind.as_str()),
                    "request_kind is a closed token ({request_kind})"
                );
                let status = json_string_value(line, "status").expect("status");
                assert!(
                    [
                        "resolved",
                        "partial",
                        "conflicting",
                        "unavailable",
                        "cycle",
                        "limit",
                    ]
                    .contains(&status.as_str()),
                    "status is a closed token ({status})"
                );
                assert!(line.contains("\"anchors\":["));
                assert!(line.contains("\"claims\":["));
                assert!(line.contains("\"derivations\":["));
                assert!(line.contains("\"diagnostics\":["));
                assert!(line.contains("\"view\":"));
            }
            Some("run") => {
                runs += 1;
                assert_eq!(json_string_value(line, "ref").as_deref(), Some("ctx:run"));
                for key in [
                    "requests",
                    "resolved",
                    "non_resolved",
                    "status_counts",
                    "limit_reached",
                    "diagnostics",
                ] {
                    assert!(line.contains(&format!("\"{key}\":")), "run has {key}");
                }
                assert!(line.contains("\"status_counts\":{"));
            }
            other => panic!("unknown context kind {other:?}"),
        }
    }
    assert!(results > 0, "the fixture emits context result lines");
    assert_eq!(runs, 1, "exactly one aggregate run line");
}

