#[test]
fn unknown_context_kind_is_refused() {
    let p = pipeline(&wrap(CONTEXT_BODY));
    let contexts = build_context_records(&p.analysis.layout, &p.mapping);
    let text = render_with_context(&p, &contexts);
    let hostile = text.replace("\"kind\":\"result\"", "\"kind\":\"bogus\"");
    assert_ne!(hostile, text, "the mutation changed a context line");
    assert_eq!(
        inspect_npa_analysis_wire(&hostile)
            .expect_err("an unknown context kind is a structural refusal")
            .kind(),
        AnalysisWireErrorKind::UnknownKind
    );
}
