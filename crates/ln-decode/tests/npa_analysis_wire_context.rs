//! T03 contract battery (M214-es3jvw S03).
//!
//! Executable core of `prd/architecture/npa-analysis-jsonl-contract.md` §8B.1
//! and §8B.3: the opt-in seventh `context` family renders into the S02
//! envelope (`render_npa_analysis_with_context`), while an empty context slice
//! stays byte-identical to the six-family S02 envelope (D662). Context lines
//! are compact sorted-key JSON carrying closed token tables, appear after the
//! diagnostics, never re-carry decoded corpus text, and a non-resolved context
//! result forces an honest `incomplete`/`context_incomplete` footer that is
//! never promoted to complete.
//!
//! Fixtures are inline synthetic WordML documents. Byte expectations are
//! handwritten oracles, never generated by the module under test. Raw decoded
//! corpus text is never logged.

