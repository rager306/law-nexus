//! T03 contract battery (M214-es3jvw S02).
//!
//! Executable core of `prd/architecture/npa-analysis-jsonl-contract.md` §8A.7:
//! over the T02 analysis block layout, the real `npa_link` and `npa_classify`
//! pipelines produce linked member, relation and classification records. Every
//! record carries a resolved fragment-qualified span or a closed refusal;
//! payload-free analyzer diagnostics survive as `diagnostic` records with
//! non-empty provenance, never swallowed and never promoted to success.
//!
//! Fixtures are inline non-legal synthetic WordML documents. Byte expectations
//! are handwritten oracles over the literal block text, never generated by the
//! module under test. Raw decoded corpus text is never logged.

use ln_decode::analysis_source_mapping::{SourceIdentity, SourceMapping};
use ln_decode::document_context::DocumentVersionRef;
use ln_decode::npa_analysis_records::{
    analyze_document, build_linked_analysis, DiagnosticKind, DiagnosticStage, DocumentAnalysis,
    SourceBoundSpan, CLASSIFY_RULE, LINK_RULE,
};
use ln_decode::npa_link::LinkDerivation;
use ln_decode::npa_link::LinkedRelationKind;
use ln_decode::reader_contract::{FragmentRef, ReaderRecordIndex};
use ln_decode::reader_projection::build_projection;
use ln_decode::source_package::{capture, Limits};

fn wrap(body: &str) -> String {
    format!(
        "<w:wordDocument xmlns:w=\"http://schemas.microsoft.com/office/word/2003/wordml\"><w:body>{body}</w:body></w:wordDocument>"
    )
}

/// Runs the real pipeline: capture -> projection -> block layout -> typed,
/// linked, relation and classification records, with a mapping that pins every
/// substrate fragment.
fn analyze(xml: &str) -> (DocumentAnalysis, SourceMapping) {
    let package = capture(xml.as_bytes(), &Limits::default()).expect("fixture must capture");
    let index = ReaderRecordIndex::new(package.records()).expect("substrate index");
    let projection = build_projection(package.records()).expect("projection must build");
    let identity = SourceIdentity::try_new(
        package.manifest().source.sha256.clone(),
        package.manifest().source.bytes,
        "law-nexus/source-package-model/v1".to_string(),
        package.footer().records_seal_hash.clone(),
        package.footer().manifest_hash.clone(),
    )
    .expect("manifest identity must be well formed");
    let version = DocumentVersionRef::try_new(
        "doc-version-1".to_string(),
        "rev-1".to_string(),
        "reader_wordml_profile/v1".to_string(),
    )
    .expect("version triple must be well formed");
    let mut mapping = SourceMapping::new(identity.clone(), version);
    for text in index.texts() {
        mapping
            .pin_fragment(
                FragmentRef::from(text.id.as_str()),
                text.value.clone(),
                &identity,
            )
            .expect("every substrate fragment must pin");
    }
    let analysis = analyze_document(&projection, &index, &mapping).expect("analysis must build");
    (analysis, mapping)
}

fn slice(mapping: &SourceMapping, span: &SourceBoundSpan) -> String {
    let resolved = mapping
        .resolve_fragment_span(&span.as_fragment_span())
        .expect("bound span must resolve");
    mapping
        .slice(&resolved)
        .expect("resolved span must slice")
        .to_string()
}

const TYPED_BODY: &str = "<w:p><w:r><w:t>Федеральный закон от 01.01.2020 N 1-ФЗ</w:t></w:r></w:p>";

// Open series head + bare `от ДАТА N` tail (RC28-F07). This pair is the
// documented `npa_link::link_series` positive.
const SERIES_BODY: &str = "<w:p><w:r><w:t>Федерального закона от 01.01.2020 N 1-ФЗ,</w:t></w:r>\
     </w:p><w:p><w:r><w:t>от 02.02.2021 N 2-ФЗ</w:t></w:r></w:p>";

const UNRESOLVED_BODY: &str =
    "<w:p><w:r><w:t>Правительство рассмотрело обращение от 01.01.2020 N 5</w:t></w:r></w:p>";

const SPLIT_BODY: &str =
    "<w:p><w:r><w:t>от 01.01.2020 N </w:t></w:r><w:r><w:t>1-ФЗ</w:t></w:r></w:p>";

// ------------------------------------------------------------- linked members #

#[test]
fn linked_member_resolves_to_the_exact_substrate_slice() {
    let (analysis, mapping) = analyze(&wrap(TYPED_BODY));
    assert_eq!(analysis.linked.len(), 1, "one anchored linked member");
    let member = &analysis.linked[0];
    assert_eq!(member.member_id, 0);
    assert_eq!(member.derivation, LinkDerivation::TypedAnchor);

    let bound = member.evidence.as_bound().expect("anchor span resolves");
    assert_eq!(slice(&mapping, bound), "от 01.01.2020 N 1-ФЗ");

    assert!(
        !member.provenance.is_empty(),
        "linked provenance is never empty"
    );
    for span in &member.provenance {
        assert!(span.is_bound(), "provenance span resolves");
    }
}

// --------------------------------------------------------------- relations #

#[test]
fn continues_series_relation_keeps_two_separate_anchors() {
    let (analysis, mapping) = analyze(&wrap(SERIES_BODY));
    assert_eq!(analysis.layout.block_count(), 2, "two primary paragraphs");
    assert_eq!(
        analysis.layout.block(0).expect("head block").text,
        "Федерального закона от 01.01.2020 N 1-ФЗ,"
    );

    let relation = analysis
        .relations
        .iter()
        .find(|relation| relation.kind == LinkedRelationKind::ContinuesSeries)
        .expect("the open head must continue into the tail");
    assert_eq!(relation.evidence.len(), 2, "two separate local anchors");
    let head = relation.evidence[0]
        .as_bound()
        .expect("head anchor resolves");
    let tail = relation.evidence[1]
        .as_bound()
        .expect("tail anchor resolves");
    assert_ne!(
        head.fragment, tail.fragment,
        "a continuation never reuses one cross-block span"
    );
    assert!(slice(&mapping, head).contains("1-ФЗ"));
    assert!(slice(&mapping, tail).contains("2-ФЗ"));
}

// ----------------------------------------------------- cross-fragment refusal #

#[test]
fn cross_fragment_linked_and_classification_spans_are_refused() {
    let (analysis, _) = analyze(&wrap(SPLIT_BODY));
    assert_eq!(
        analysis.layout.block(0).expect("one block").text,
        "от 01.01.2020 N 1-ФЗ"
    );
    let member = analysis
        .linked
        .iter()
        .find(|member| member.member_id == 0)
        .expect("the member is emitted, not dropped");
    assert_eq!(
        member.evidence.refusal_token(),
        Some("cross_fragment"),
        "a span straddling two fragments is a closed refusal, never rebased"
    );
    let classification = analysis
        .classifications
        .iter()
        .find(|record| record.member_id == 0)
        .expect("the member is still classified");
    assert_eq!(
        classification.evidence.refusal_token(),
        Some("cross_fragment"),
        "classification keeps the same closed refusal"
    );
}

// ---------------------------------------------------- classification records #

#[test]
fn classification_record_carries_axes_and_a_resolved_span() {
    let (analysis, mapping) = analyze(&wrap(TYPED_BODY));
    let record = analysis
        .classifications
        .iter()
        .find(|record| record.member_id == 0)
        .expect("member 0 is classified");
    let bound = record.evidence.as_bound().expect("evidence resolves");
    assert_eq!(slice(&mapping, bound), "от 01.01.2020 N 1-ФЗ");

    for token in [
        record.graph.as_str(),
        record.legal_class.as_str(),
        record.competence.as_str(),
        record.identity_key.as_str(),
    ] {
        assert!(!token.is_empty(), "axis token is present");
    }
    assert!(
        !record.why.is_empty(),
        "classification keeps the producer why"
    );
}

// -------------------------------------------------------------- diagnostics #

#[test]
fn link_diagnostics_are_never_swallowed() {
    let (analysis, _) = analyze(&wrap(TYPED_BODY));
    let diagnostic = analysis
        .diagnostics
        .iter()
        .find(|diagnostic| diagnostic.stage == DiagnosticStage::Link)
        .expect("a body with no letterhead emits a link diagnostic");
    assert_eq!(diagnostic.kind, DiagnosticKind::HeadUnavailable);
    assert_eq!(diagnostic.rule, LINK_RULE);
    assert!(
        diagnostic.span.is_none(),
        "LinkDiagnostic carries no producer span"
    );
    assert!(
        !diagnostic.refs.is_empty(),
        "provenance survives the missing span"
    );
    assert_eq!(diagnostic.refs[0].family, "document");
}

#[test]
fn classification_diagnostics_are_never_swallowed() {
    let (analysis, _) = analyze(&wrap(UNRESOLVED_BODY));
    let diagnostic = analysis
        .diagnostics
        .iter()
        .find(|diagnostic| diagnostic.stage == DiagnosticStage::Classification)
        .expect("an untyped anchor emits a classification diagnostic");
    assert_eq!(diagnostic.kind, DiagnosticKind::TypeMissing);
    assert_eq!(diagnostic.rule, CLASSIFY_RULE);
    assert!(diagnostic.span.is_none());
    assert!(!diagnostic.refs.is_empty());
}

// ------------------------------------------------------------- replay rules #

#[test]
fn linked_analysis_is_deterministic_and_read_only() {
    let (analysis, mapping) = analyze(&wrap(SERIES_BODY));
    let layout_before = analysis.layout.clone();

    let first = build_linked_analysis(&analysis.layout, &mapping);
    let second = build_linked_analysis(&analysis.layout, &mapping);

    assert_eq!(first, second, "replay yields the same records in order");
    assert_eq!(first.members, analysis.linked);
    assert_eq!(first.relations, analysis.relations);
    assert_eq!(first.classifications, analysis.classifications);
    assert_eq!(
        analysis.layout, layout_before,
        "the analysis layout is not mutated by linking or classification"
    );
}

#[test]
fn diagnostics_have_unique_global_indices() {
    let (analysis, _) = analyze(&wrap(SERIES_BODY));
    for (position, diagnostic) in analysis.diagnostics.iter().enumerate() {
        assert_eq!(
            diagnostic.index, position,
            "diagnostic index is its position"
        );
    }
    // The link pass must have contributed at least the letterhead diagnostic.
    assert!(
        analysis
            .diagnostics
            .iter()
            .any(|diagnostic| diagnostic.stage == DiagnosticStage::Link),
        "the combined stream keeps the link diagnoses"
    );
}

#[test]
fn producer_rule_tokens_are_stable() {
    assert_eq!(LINK_RULE, "npa_link::build_linked_document");
    assert_eq!(CLASSIFY_RULE, "npa_classify::classify_members");

    assert_eq!(
        DiagnosticKind::TypeNotInherited.as_str(),
        "type_not_inherited"
    );
    assert_eq!(
        DiagnosticKind::HeadFamilyCarryRefused.as_str(),
        "head_family_carry_refused"
    );
    assert_eq!(
        DiagnosticKind::AliasWithoutDeclaration.as_str(),
        "alias_without_declaration"
    );
    assert_eq!(DiagnosticKind::HeadUnavailable.as_str(), "head_unavailable");
    assert_eq!(DiagnosticKind::SpanInvalid.as_str(), "span_invalid");
    assert_eq!(DiagnosticKind::TypeMissing.as_str(), "type_missing");
}
