//! T02 contract battery (M214-es3jvw S02).
//!
//! Executable core of `prd/architecture/npa-analysis-jsonl-contract.md` §8A.3:
//! a reader primary view becomes an analysis block whose text is the ordered
//! concatenation of its source-fragment segments (derived segments excluded),
//! and a local analyzer span is localized to exactly one pinned fragment (or a
//! closed refusal). Typed provenance (`unresolved`/`alternatives`/
//! `type_evidence`) and anchor diagnostics survive with a source ref.
//!
//! Fixtures are inline non-legal synthetic WordML documents. Byte expectations
//! are handwritten oracles over the literal block text, never generated by the
//! module under test. Raw decoded corpus text is never logged.

use ln_decode::analysis_source_mapping::{SourceIdentity, SourceMapping};
use ln_decode::document_context::DocumentVersionRef;
use ln_decode::npa_analysis_records::{
    analyze_typed, AnalysisBlock, AnalysisBlockLayout, AnalysisRefusalKind, BlockSegment,
    DiagnosticKind, DiagnosticStage, TypedAnalysis,
};
use ln_decode::npa_anchor::{LocalSpan, RejectReason};
use ln_decode::npa_typed::TypeDerivation;
use ln_decode::reader_contract::{FragmentRef, ReaderRecordIndex};
use ln_decode::reader_projection::{build_projection, ViewId};
use ln_decode::source_package::{capture, Limits};

fn wrap(body: &str) -> String {
    format!(
        "<w:wordDocument xmlns:w=\"http://schemas.microsoft.com/office/word/2003/wordml\"><w:body>{body}</w:body></w:wordDocument>"
    )
}

/// Runs the real pipeline: capture -> projection -> block layout -> typed
/// records, with a mapping that pins every substrate fragment.
fn analyze(xml: &str) -> (TypedAnalysis, SourceMapping) {
    let package = capture(xml.as_bytes(), &Limits::default()).expect("fixture must capture");
    let index = ReaderRecordIndex::new(package.records()).expect("substrate index");
    let projection = build_projection(package.records()).expect("projection must build");
    let identity = SourceIdentity::try_new(
        package.manifest().source.sha256.clone(),
        package.manifest().source.bytes,
        "law-nexus/source-package-model/v1".to_string(),
        package.footer().records_seal_hash.clone(),
        package.footer().manifest_hash.clone(),
    )
    .expect("manifest identity must be well formed");
    let version = DocumentVersionRef::try_new(
        "doc-version-1".to_string(),
        "rev-1".to_string(),
        "reader_wordml_profile/v1".to_string(),
    )
    .expect("version triple must be well formed");
    let mut mapping = SourceMapping::new(identity.clone(), version);
    for text in index.texts() {
        mapping
            .pin_fragment(
                FragmentRef::from(text.id.as_str()),
                text.value.clone(),
                &identity,
            )
            .expect("every substrate fragment must pin");
    }
    let analysis = analyze_typed(&projection, &index, &mapping).expect("typed analysis must build");
    (analysis, mapping)
}

fn slice(
    mapping: &SourceMapping,
    span: &ln_decode::npa_analysis_records::SourceBoundSpan,
) -> String {
    let resolved = mapping
        .resolve_fragment_span(&span.as_fragment_span())
        .expect("bound span must resolve");
    mapping
        .slice(&resolved)
        .expect("resolved span must slice")
        .to_string()
}

// ------------------------------------------------------------- block layout #

const TWO_RUNS: &str = "<w:p><w:r><w:t>Alpha</w:t></w:r><w:r><w:t>Beta</w:t></w:r></w:p>";

#[test]
fn block_layout_concatenates_source_fragments_in_segment_order() {
    let (analysis, _) = analyze(&wrap(TWO_RUNS));
    assert_eq!(analysis.layout.block_count(), 1);
    let block = analysis.layout.block(0).expect("one block");
    assert_eq!(block.text, "AlphaBeta");
    assert_eq!(block.segments.len(), 2);
    assert_eq!(
        (block.segments[0].block_start, block.segments[0].block_end),
        (0, 5)
    );
    assert_eq!(
        (block.segments[1].block_start, block.segments[1].block_end),
        (5, 9)
    );
    assert_ne!(
        block.segments[0].fragment.as_str(),
        block.segments[1].fragment.as_str()
    );
}

const TAB_WITH_TEXT: &str = "<w:p><w:r><w:t>Alpha</w:t><w:tab/></w:r></w:p>";

#[test]
fn block_layout_excludes_derived_segments() {
    let (analysis, _) = analyze(&wrap(TAB_WITH_TEXT));
    let block = analysis.layout.block(0).expect("one block");
    assert_eq!(block.text, "Alpha", "the derived tab is not block text");
    assert_eq!(block.segments.len(), 1, "only the source-fragment segment");
}

const TAB_ONLY: &str = "<w:p><w:r><w:tab/></w:r></w:p>";

#[test]
fn empty_primary_view_is_not_an_analysis_block() {
    let (analysis, _) = analyze(&wrap(TAB_ONLY));
    assert_eq!(
        analysis.layout.block_count(),
        0,
        "a block with no source-fragment text is skipped"
    );
}

// ------------------------------------------------------------ localization #

fn manual_layout() -> AnalysisBlockLayout {
    AnalysisBlockLayout {
        blocks: vec![AnalysisBlock {
            index: 0,
            view: ViewId::new("v0"),
            text: "abcdef".to_string(),
            segments: vec![
                BlockSegment {
                    fragment: FragmentRef::new("t0"),
                    block_start: 0,
                    block_end: 3,
                    fragment_start: 0,
                    fragment_end: 3,
                },
                BlockSegment {
                    fragment: FragmentRef::new("t1"),
                    block_start: 3,
                    block_end: 6,
                    fragment_start: 0,
                    fragment_end: 3,
                },
            ],
        }],
    }
}

#[test]
fn local_span_localizes_to_exactly_one_fragment() {
    let layout = manual_layout();
    let bound = layout
        .localize(LocalSpan {
            block: 0,
            start: 4,
            end: 6,
        })
        .expect("a span inside the second segment localizes");
    assert_eq!(bound.fragment, FragmentRef::new("t1"));
    assert_eq!((bound.start, bound.end), (1, 3));
}

#[test]
fn cross_fragment_span_is_a_closed_refusal() {
    let layout = manual_layout();
    let refusal = layout
        .localize(LocalSpan {
            block: 0,
            start: 2,
            end: 4,
        })
        .expect_err("a span straddling two fragments must be refused");
    assert_eq!(refusal.token(), "cross_fragment");
}

#[test]
fn invalid_out_of_bounds_and_unmapped_spans_are_refused() {
    let layout = manual_layout();

    assert_eq!(
        layout
            .localize(LocalSpan {
                block: 0,
                start: 2,
                end: 2,
            })
            .expect_err("empty span")
            .token(),
        "invalid_span"
    );
    assert_eq!(
        layout
            .localize(LocalSpan {
                block: 0,
                start: 0,
                end: 7,
            })
            .expect_err("span past the block text")
            .token(),
        "out_of_bounds"
    );
    assert_eq!(
        layout
            .localize(LocalSpan {
                block: 9,
                start: 0,
                end: 1,
            })
            .expect_err("unknown block")
            .token(),
        "unmapped_block"
    );
}

// ----------------------------------------------------------- typed records #

const TYPED_BODY: &str = "<w:p><w:r><w:t>Федеральный закон от 01.01.2020 N 1-ФЗ</w:t></w:r></w:p>";

#[test]
fn typed_span_resolves_to_the_exact_substrate_slice() {
    let (analysis, mapping) = analyze(&wrap(TYPED_BODY));
    assert_eq!(analysis.members.len(), 1);
    let member = &analysis.members[0];
    assert_eq!(member.number, "1-ФЗ");
    assert_eq!(member.date, "01.01.2020");
    assert_eq!(member.derivation, TypeDerivation::WrittenHere);
    assert!(!member.unresolved);

    let bound = member.span.as_bound().expect("anchor span resolves");
    assert_eq!(
        bound.fragment,
        analysis.layout.block(0).unwrap().segments[0].fragment
    );
    assert_eq!(slice(&mapping, bound), "от 01.01.2020 N 1-ФЗ");

    let evidence = member
        .type_evidence
        .as_ref()
        .expect("winner must carry type_evidence");
    let evidence = evidence.as_bound().expect("evidence resolves");
    assert_eq!(slice(&mapping, evidence), "Федеральный закон");
}

const UNRESOLVED_BODY: &str =
    "<w:p><w:r><w:t>Правительство рассмотрело обращение от 01.01.2020 N 5</w:t></w:r></w:p>";

#[test]
fn unresolved_member_keeps_its_provenance() {
    let (analysis, _) = analyze(&wrap(UNRESOLVED_BODY));
    let member = analysis
        .members
        .iter()
        .find(|member| member.number == "5")
        .expect("the anchor is still emitted");
    assert!(member.unresolved);
    assert_eq!(member.derivation, TypeDerivation::Unresolved);
    assert_eq!(member.type_name, "");
    assert!(member.type_evidence.is_none());
    assert!(member.alternatives.is_empty());
    assert!(member.span.is_bound(), "the anchor span still resolves");
}

const ALTERNATIVES_BODY: &str =
    "<w:p><w:r><w:t>дополнительное соглашение к контракту от 23.03.2023 N 2</w:t></w:r></w:p>";

#[test]
fn competing_hypotheses_and_type_evidence_are_preserved_with_spans() {
    let (analysis, mapping) = analyze(&wrap(ALTERNATIVES_BODY));
    let member = analysis
        .members
        .iter()
        .find(|member| member.number == "2")
        .expect("member N 2");
    assert_eq!(member.type_name, "контракт");
    assert_eq!(member.derivation, TypeDerivation::WrittenHere);

    let canon: Vec<&str> = member
        .alternatives
        .iter()
        .map(|alternative| alternative.canon.as_str())
        .collect();
    assert!(canon.contains(&"соглашение"), "{canon:?}");
    for alternative in &member.alternatives {
        let bound = alternative
            .span
            .as_bound()
            .unwrap_or_else(|| panic!("alternative {} must resolve", alternative.canon));
        let resolved_slice = slice(&mapping, bound);
        assert!(
            !resolved_slice.is_empty(),
            "alternative {} keeps a non-empty source ref",
            alternative.canon
        );
        assert!(
            alternative.canon.starts_with(&resolved_slice),
            "the hypothesis head span is a prefix of its canon: {:?} vs {:?}",
            resolved_slice,
            alternative.canon
        );
    }
}

const SPLIT_BODY: &str =
    "<w:p><w:r><w:t>от 01.01.2020 N </w:t></w:r><w:r><w:t>1-ФЗ</w:t></w:r></w:p>";

#[test]
fn cross_fragment_typed_span_becomes_a_refused_record_not_a_drop() {
    let (analysis, _) = analyze(&wrap(SPLIT_BODY));
    assert_eq!(
        analysis.layout.block(0).expect("one block").text,
        "от 01.01.2020 N 1-ФЗ"
    );
    assert_eq!(
        analysis.members.len(),
        1,
        "the member is emitted, not dropped"
    );
    assert_eq!(
        analysis.members[0].span.refusal_token(),
        Some("cross_fragment"),
        "a span straddling two fragments is a closed refusal, never rebased"
    );
}

// ---------------------------------------------------------- diagnostics #

const REJECTED_BODY: &str =
    "<w:p><w:r><w:t>Письмо (вх. N 5 от 02.02.2020 N 6) рассмотрено</w:t></w:r></w:p>";

#[test]
fn rejected_anchor_diagnostic_is_mapped_not_swallowed() {
    let (analysis, _) = analyze(&wrap(REJECTED_BODY));
    assert!(
        analysis.members.is_empty(),
        "a guard-rejected anchor must not mint a member"
    );
    let diagnostic = analysis
        .diagnostics
        .iter()
        .find(|diagnostic| diagnostic.kind == DiagnosticKind::RejectedAnchor)
        .expect("the rejected anchor diagnostic survives as a record");
    assert_eq!(diagnostic.stage, DiagnosticStage::Anchor);
    assert_eq!(diagnostic.reject_reason, Some(RejectReason::Inbound));
    assert_eq!(diagnostic.rule, "npa_typed::scan_typed_diagnosed");
    assert!(!diagnostic.refs.is_empty(), "provenance is never empty");
    assert!(diagnostic.span.is_some());
    assert_eq!(diagnostic.block, Some(0));
}

const DUPLICATE_BODY: &str =
    "<w:p><w:r><w:t>от 01.01.2020 N 1 и от 01.01.2020 N 1</w:t></w:r></w:p>";

#[test]
fn duplicate_occurrence_diagnostic_names_its_members() {
    let (analysis, _) = analyze(&wrap(DUPLICATE_BODY));
    assert_eq!(analysis.members.len(), 2, "occurrences are not merged");
    let diagnostic = analysis
        .diagnostics
        .iter()
        .find(|diagnostic| diagnostic.kind == DiagnosticKind::DuplicateOccurrence)
        .expect("duplicate occurrence diagnostic");
    assert!(
        diagnostic
            .refs
            .iter()
            .any(|reference| reference.family == "member" && reference.reference == "mt:0"),
        "the diagnostic names the member it concerns: {:?}",
        diagnostic.refs
    );
}

// -------------------------------------------------------- token vocabulary #

#[test]
fn refusal_and_diagnostic_tokens_are_the_closed_vocabulary() {
    assert_eq!(
        AnalysisRefusalKind::CrossFragment.as_str(),
        "cross_fragment"
    );
    assert_eq!(AnalysisRefusalKind::OutOfBounds.as_str(), "out_of_bounds");
    assert_eq!(
        AnalysisRefusalKind::UnmappedBlock.as_str(),
        "unmapped_block"
    );
    assert_eq!(AnalysisRefusalKind::InvalidSpan.as_str(), "invalid_span");
    assert_eq!(AnalysisRefusalKind::LimitReached.as_str(), "limit_reached");

    assert_eq!(DiagnosticStage::Anchor.as_str(), "anchor");
    assert_eq!(DiagnosticStage::Link.as_str(), "link");
    assert_eq!(DiagnosticStage::Classification.as_str(), "classification");

    assert_eq!(DiagnosticKind::InvalidSpan.as_str(), "invalid_span");
    assert_eq!(DiagnosticKind::RejectedAnchor.as_str(), "rejected_anchor");
    assert_eq!(
        DiagnosticKind::DuplicateOccurrence.as_str(),
        "duplicate_occurrence"
    );
    assert_eq!(DiagnosticKind::UnknownKind.as_str(), "unknown_kind");
}
