// ------------------------------------ 5. closed refusal at a derived boundary #

#[test]
fn crossing_a_derived_boundary_is_a_closed_refusal_never_a_bound_span() {
    let (analysis, mapping) = analyze(&wrap(TAB_BOUNDARY));
    let layout = &analysis.layout;
    let block = layout.block(0).expect("one block");

    // Byte map: "Федеральный" [0,22), tab [22,23), "закон" [23,33).
    assert_eq!(
        (
            block.boundaries[0].block_start,
            block.boundaries[0].block_end
        ),
        (22, 23)
    );

    let crossing = LocalSpan {
        block: 0,
        start: 0,
        end: 33,
    };
    let refusal = layout
        .localize(crossing)
        .expect_err("a span over the derived tab must be refused");
    assert_eq!(
        refusal.token(),
        "derived_separator",
        "the derived boundary is a closed refusal, never rebound"
    );

    let resolved = ln_decode::npa_analysis_records::resolve_span(layout, &mapping, crossing)
        .expect_err("resolve_span must refuse too");
    assert_eq!(resolved.token(), "derived_separator");

    let left = LocalSpan {
        block: 0,
        start: 0,
        end: 22,
    };
    let left_bound = layout.localize(left).expect("left source span resolves");
    let left_resolved =
        ln_decode::npa_analysis_records::resolve_span(layout, &mapping, left).expect("resolves");
    assert_eq!(left_bound.fragment, left_resolved.fragment);
    assert_eq!(
        slice(&mapping, &SourceRef::Bound(left_resolved)),
        "Федеральный"
    );

    let right = LocalSpan {
        block: 0,
        start: 23,
        end: 33,
    };
    let right_resolved =
        ln_decode::npa_analysis_records::resolve_span(layout, &mapping, right).expect("resolves");
    assert_eq!(slice(&mapping, &SourceRef::Bound(right_resolved)), "закон");
}

// ------------------------------------------- 6. boundaries are typed and ordered #

const MIXED_CONTROLS: &str = "<w:p><w:r><w:t>статья</w:t><w:tab/><w:t>5</w:t><w:br/><w:t>часть</w:t><w:br w:type=\"page\"/><w:t>2</w:t></w:r></w:p>";

#[test]
fn derived_boundaries_carry_reader_controls_in_document_order() {
    let (analysis, _) = analyze(&wrap(MIXED_CONTROLS));
    let block = analysis.layout.block(0).expect("one block");
    assert_eq!(block.text, "статья\t5\nчасть\n2");
    assert_eq!(block.segments.len(), 4, "four source-fragment segments");

    let kinds: Vec<ReaderDerivedKind> = block
        .boundaries
        .iter()
        .map(|boundary| boundary.kind)
        .collect();
    assert_eq!(
        kinds,
        vec![
            ReaderDerivedKind::Tab,
            ReaderDerivedKind::LineBreak,
            ReaderDerivedKind::PageBreak
        ],
        "typed boundaries keep document order"
    );

    let offsets: Vec<(usize, usize)> = block
        .boundaries
        .iter()
        .map(|boundary| (boundary.block_start, boundary.block_end))
        .collect();
    assert_eq!(offsets, vec![(12, 13), (14, 15), (25, 26)]);
}
