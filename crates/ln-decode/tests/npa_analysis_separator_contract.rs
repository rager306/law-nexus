//! T03 separator battery (M221-wbslul S02).
//!
//! Durable red-green equivalent of `scripts/m214_readiness_probe.rs` for F02:
//! the reader primary view keeps its derived separators (`w:tab`, `w:br`) as an
//! explicit typed boundary inside the analysis block text, so an analyzer span
//! that crosses such a boundary is a closed `derived_separator` refusal rather
//! than a silently re-glued lexeme.
//!
//! This battery runs the real pipeline (`capture` -> `ReaderRecordIndex` ->
//! `build_projection` -> `SourceMapping` -> `analyze_typed`) over inline
//! synthetic WordML. Byte expectations are handwritten literal oracles over the
//! block text, never generated by the module under test. Raw decoded corpus text
//! is never logged.

use ln_decode::analysis_source_mapping::{SourceIdentity, SourceMapping};
use ln_decode::document_context::DocumentVersionRef;
use ln_decode::npa_analysis_records::{SourceRef, TypedAnalysis, analyze_typed};
use ln_decode::npa_anchor::LocalSpan;
use ln_decode::reader_contract::{FragmentRef, ReaderDerivedKind, ReaderRecordIndex};
use ln_decode::reader_projection::build_projection;
use ln_decode::source_package::{Limits, capture};

fn wrap(body: &str) -> String {
    format!(
        "<w:wordDocument xmlns:w=\"http://schemas.microsoft.com/office/word/2003/wordml\"><w:body>{body}</w:body></w:wordDocument>"
    )
}

/// Runs the real pipeline: capture -> projection -> block layout -> typed
/// records, with a mapping that pins every substrate fragment.
fn analyze(xml: &str) -> (TypedAnalysis, SourceMapping) {
    let package = capture(xml.as_bytes(), &Limits::default()).expect("fixture must capture");
    let index = ReaderRecordIndex::new(package.records()).expect("substrate index");
    let projection = build_projection(package.records()).expect("projection must build");
    let identity = SourceIdentity::try_new(
        package.manifest().source.sha256.clone(),
        package.manifest().source.bytes,
        "law-nexus/source-package-model/v1".to_string(),
        package.footer().records_seal_hash.clone(),
        package.footer().manifest_hash.clone(),
    )
    .expect("manifest identity must be well formed");
    let version = DocumentVersionRef::try_new(
        "doc-version-1".to_string(),
        "rev-1".to_string(),
        "reader_wordml_profile/v1".to_string(),
    )
    .expect("version triple must be well formed");
    let mut mapping = SourceMapping::new(identity.clone(), version);
    for text in index.texts() {
        mapping
            .pin_fragment(
                FragmentRef::from(text.id.as_str()),
                text.value.clone(),
                &identity,
            )
            .expect("every substrate fragment must pin");
    }
    let analysis = analyze_typed(&projection, &index, &mapping).expect("typed analysis must build");
    (analysis, mapping)
}

fn slice(mapping: &SourceMapping, span: &SourceRef) -> String {
    let bound = span.as_bound().expect("span must be bound");
    let resolved = mapping
        .resolve_fragment_span(&bound.as_fragment_span())
        .expect("bound span must resolve");
    mapping
        .slice(&resolved)
        .expect("resolved span must slice")
        .to_string()
}

/// The single typed member of a one-member analysis.
fn only_member(analysis: &TypedAnalysis) -> &ln_decode::npa_analysis_records::TypedMemberRecord {
    assert_eq!(analysis.members.len(), 1, "exactly one typed member");
    &analysis.members[0]
}

// ------------------------------------------------ 1. semantic red-green (F02) #

const SPLIT_BY_TAB: &str =
    "<w:p><w:r><w:t>Федеральный</w:t><w:tab/><w:t>закон от 05.04.2013 № 44-ФЗ</w:t></w:r></w:p>";
const COLLAPSED: &str = "<w:p><w:r><w:t>Федеральныйзакон от 05.04.2013 № 44-ФЗ</w:t></w:r></w:p>";

#[test]
fn derived_separator_preserves_the_lexeme_but_refuses_the_crossing_type_span() {
    let (analysis, _) = analyze(&wrap(SPLIT_BY_TAB));
    let block = analysis.layout.block(0).expect("one block");
    assert_eq!(
        block.text, "Федеральный\tзакон от 05.04.2013 № 44-ФЗ",
        "the derived tab survives as the separator literal"
    );

    let member = only_member(&analysis);
    assert_eq!(member.number, "44-ФЗ");
    assert_eq!(
        member.type_name, "Федеральный закон",
        "the tab-separated type is still resolved as one lexeme"
    );
    assert!(!member.unresolved, "the type hypothesis survives the tab");

    let evidence = member
        .type_evidence
        .as_ref()
        .expect("winner carries type_evidence");
    assert_eq!(
        evidence.refusal_token(),
        Some("derived_separator"),
        "the type span crosses the tab: a closed refusal, never rebased"
    );
    assert!(matches!(evidence, SourceRef::Refused(_)));

    assert!(
        member.span.is_bound(),
        "the date/number anchor lives inside the second source fragment"
    );
}

#[test]
fn collapsed_control_breaks_the_lexeme_and_leaves_the_type_unresolved() {
    let (analysis, _) = analyze(&wrap(COLLAPSED));
    let block = analysis.layout.block(0).expect("one block");
    assert_eq!(block.text, "Федеральныйзакон от 05.04.2013 № 44-ФЗ");

    let member = only_member(&analysis);
    assert_eq!(member.number, "44-ФЗ");
    assert_eq!(member.type_name, "", "no type survives the collapsed word");
    assert!(
        member.unresolved,
        "the collapsed control destroys the Federal-law type"
    );
    assert!(member.type_evidence.is_none());
}

// ----------------------------------------------- 2. run splitting (metamorphic) #

const ONE_RUN: &str = "<w:p><w:r><w:t>Alpha Beta</w:t></w:r></w:p>";
const TWO_RUNS: &str = "<w:p><w:r><w:t>Alpha </w:t></w:r><w:r><w:t>Beta</w:t></w:r></w:p>";

#[test]
fn run_splitting_is_metamorphic_over_the_block_text() {
    let (one, _) = analyze(&wrap(ONE_RUN));
    let (two, _) = analyze(&wrap(TWO_RUNS));

    let one_block = one.layout.block(0).expect("one block");
    let two_block = two.layout.block(0).expect("one block");

    assert_eq!(one_block.text, "Alpha Beta");
    assert_eq!(two_block.text, "Alpha Beta", "byte-equal block text");
    assert!(one_block.boundaries.is_empty(), "no derived control");
    assert!(two_block.boundaries.is_empty(), "no derived control");

    assert_eq!(one_block.segments.len(), 1);
    assert_eq!(two_block.segments.len(), 2, "two source-fragment segments");
    assert_eq!(
        one.members.len(),
        two.members.len(),
        "splitting a run does not change the typed result"
    );
}

// ---------------------------------------------- 3. tab / space / br equivalence #

const SPACE_BOUNDARY: &str =
    "<w:p><w:r><w:t>Федеральный закон от 05.04.2013 № 44-ФЗ</w:t></w:r></w:p>";
const TAB_BOUNDARY: &str =
    "<w:p><w:r><w:t>Федеральный</w:t><w:tab/><w:t>закон от 05.04.2013 № 44-ФЗ</w:t></w:r></w:p>";
const LINE_BREAK_BOUNDARY: &str =
    "<w:p><w:r><w:t>Федеральный</w:t><w:br/><w:t>закон от 05.04.2013 № 44-ФЗ</w:t></w:r></w:p>";

#[test]
fn space_tab_and_break_agree_on_the_lexeme_and_differ_only_at_the_boundary() {
    let (space, space_mapping) = analyze(&wrap(SPACE_BOUNDARY));
    let (tab, _) = analyze(&wrap(TAB_BOUNDARY));
    let (line_break, _) = analyze(&wrap(LINE_BREAK_BOUNDARY));

    let space_block = space.layout.block(0).expect("one block");
    let tab_block = tab.layout.block(0).expect("one block");
    let break_block = line_break.layout.block(0).expect("one block");

    assert_eq!(
        space_block.text, "Федеральный закон от 05.04.2013 № 44-ФЗ",
        "a space inside <w:t> is ordinary source text"
    );
    assert_eq!(tab_block.text, "Федеральный\tзакон от 05.04.2013 № 44-ФЗ");
    assert_eq!(break_block.text, "Федеральный\nзакон от 05.04.2013 № 44-ФЗ");

    let space_member = only_member(&space);
    let tab_member = only_member(&tab);
    let break_member = only_member(&line_break);

    for member in [space_member, tab_member, break_member] {
        assert_eq!(member.number, "44-ФЗ");
        assert_eq!(member.type_name, "Федеральный закон");
        assert!(!member.unresolved);
    }

    assert!(space_block.boundaries.is_empty(), "space is not a control");
    assert_eq!(tab_block.boundaries.len(), 1);
    assert_eq!(tab_block.boundaries[0].kind, ReaderDerivedKind::Tab);
    assert_eq!(break_block.boundaries.len(), 1);
    assert_eq!(break_block.boundaries[0].kind, ReaderDerivedKind::LineBreak);

    let space_evidence = space_member
        .type_evidence
        .as_ref()
        .expect("space type evidence");
    assert!(
        space_evidence.is_bound(),
        "the space-spanning type resolves to one fragment"
    );
    assert_eq!(slice(&space_mapping, space_evidence), "Федеральный закон");

    for member in [tab_member, break_member] {
        let evidence = member.type_evidence.as_ref().expect("type evidence");
        assert_eq!(evidence.refusal_token(), Some("derived_separator"));
        assert!(matches!(evidence, SourceRef::Refused(_)));
    }
}

