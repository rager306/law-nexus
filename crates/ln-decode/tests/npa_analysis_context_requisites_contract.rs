fn wrap(body: &str) -> String {
    format!(
        "<w:wordDocument xmlns:w=\"http://schemas.microsoft.com/office/word/2003/wordml\"><w:body>{body}</w:body></w:wordDocument>"
    )
}

/// Runs the real pipeline: capture -> projection -> block layout, with a
/// mapping that pins every substrate fragment. Returns the layout, the pinned
/// mapping and the substrate index (needed to re-check exact slices).
fn pipeline(xml: &str) -> (AnalysisBlockLayout, SourceMapping, ReaderRecordIndex) {
    let package = capture(xml.as_bytes(), &Limits::default()).expect("fixture must capture");
    let index = ReaderRecordIndex::new(package.records()).expect("substrate index");
    let projection = build_projection(package.records()).expect("projection must build");
    let identity = SourceIdentity::try_new(
        package.manifest().source.sha256.clone(),
        package.manifest().source.bytes,
        "law-nexus/source-package-model/v1".to_string(),
        package.footer().records_seal_hash.clone(),
        package.footer().manifest_hash.clone(),
    )
    .expect("manifest identity must be well formed");
    let version = DocumentVersionRef::try_new(
        "doc-version-1".to_string(),
        "rev-1".to_string(),
        "reader_wordml_profile/v1".to_string(),
    )
    .expect("version triple must be well formed");
    let mut mapping = SourceMapping::new(identity.clone(), version);
    for text in index.texts() {
        mapping
            .pin_fragment(
                FragmentRef::from(text.id.as_str()),
                text.value.clone(),
                &identity,
            )
            .expect("every substrate fragment must pin");
    }
    let layout =
        build_analysis_block_layout(&projection, &index).expect("analysis layout must build");
    (layout, mapping, index)
}

fn result_records(records: &[ContextRecord]) -> Vec<&ContextResultRecord> {
    records
        .iter()
        .filter_map(|record| match record {
            ContextRecord::Result(result) => Some(result),
            ContextRecord::Run(_) => None,
        })
        .collect()
}

fn requisites_result(records: &[ContextRecord]) -> Option<&ContextResultRecord> {
    result_records(records)
        .into_iter()
        .find(|record| record.request_kind == ContextRequestKind::CurrentDocumentRequisites)
}

/// Asserts a bound anchor slices to the exact substrate UTF-8 range and returns
/// that slice; a refused anchor returns `None`.
fn exact_slice(
    mapping: &SourceMapping,
    index: &ReaderRecordIndex,
    anchor: &SourceRef,
) -> Option<String> {
    let bound = anchor.as_bound()?;
    let resolved = mapping
        .resolve_fragment_span(&bound.as_fragment_span())
        .expect("bound anchor must resolve through the seam");
    let slice = mapping
        .slice(&resolved)
        .expect("bound anchor must slice")
        .to_string();
    let substrate = index
        .text(bound.fragment.as_str())
        .expect("anchor fragment must exist");
    assert_eq!(
        slice,
        substrate.value[bound.start..bound.end],
        "a bound context anchor must equal the exact substrate slice"
    );
    Some(slice)
}

// A recognized inline `Приказ` letterhead (block 0) and a heading block (block
// 1) that carries a non-empty this-ref surface (`настоящего Федерального
// закона`) and a structural frame. The letterhead supplies the `Type` claim,
// so the emitted requisites request resolves. The surface noun is not itself a
// legal marker, so the heading still has exactly one marker.
const AUTHORIZED_BODY: &str = "<w:p><w:r><w:t>Приказ Минэкономразвития России от 02.10.2013 N 567</w:t></w:r></w:p>\
     <w:p><w:r><w:t>Статья 2. Настоящего Федерального закона</w:t></w:r></w:p>";

// A this-ref surface with no letterhead: the request is emitted but stays
// `unavailable(missing_current_requisites)`.
const THIS_REF_ONLY_BODY: &str =
    "<w:p><w:r><w:t>Статья 1. Настоящего Федерального закона</w:t></w:r></w:p>";

// No this-ref surface at all: the requisites request must not be emitted.
const NO_THIS_REF_BODY: &str =
    "<w:p><w:r><w:t>Федеральный закон от 01.01.2020 N 1-ФЗ</w:t></w:r></w:p>";

// The RC28-F07 positive continuation pair: a proven act-type head block and a
// later bare `от ДАТА N` open tail, which mints exactly one `ContinuesSeries`
// overlay edge (`block-0-frame-0` -> `block-1-frame-0`).
const CONTINUATION_BODY: &str = "<w:p><w:r><w:t>Действующее законодательство и федеральный закон от 01.01.2020 N 1-ФЗ</w:t></w:r></w:p>\
     <w:p><w:r><w:t>от 02.02.2021 N 2-ФЗ</w:t></w:r></w:p>";

// ------------------------------------------------------ §8C.1 authorized #

#[test]
fn authorized_letterhead_authorizes_current_document_requisites() {
    let (layout, mapping, index) = pipeline(&wrap(AUTHORIZED_BODY));
    let records = build_context_records(&layout, &mapping);
    let result = requisites_result(&records)
        .expect("a this-ref surface with a letterhead must emit one requisites request");

    assert_eq!(result.status, ContextStatus::Resolved);
    assert_eq!(result.claims.len(), 1, "exactly one authorized claim");
    let claim = &result.claims[0];
    assert_eq!(
        claim.derivation,
        DerivationSource::AuthorizedCurrentDocumentRequisites
    );
    assert_eq!(claim.claim_status, ContextClaimStatus::Inherited);
    assert!(
        result.diagnostics.is_empty(),
        "an authorized requisites result carries no diagnostics"
    );

    let slice = exact_slice(&mapping, &index, &claim.anchor)
        .expect("the authorized claim anchor must be bound to a real span");
    assert!(!slice.is_empty(), "the claim anchor slice is non-empty");
}

// ------------------------------------------------ §8C.2 missing sidecar #

#[test]
fn this_ref_surface_without_letterhead_is_unavailable() {
    let (layout, mapping, _) = pipeline(&wrap(THIS_REF_ONLY_BODY));
    let records = build_context_records(&layout, &mapping);
    let result = requisites_result(&records)
        .expect("a this-ref surface must emit a requisites request even without a letterhead");

    assert_eq!(result.status, ContextStatus::Unavailable);
    assert_eq!(
        result.diagnostics,
        vec![ContextDiagnostic::MissingCurrentRequisites]
    );
    assert!(
        result.claims.is_empty(),
        "an unavailable requisites result carries no claim"
    );

    let run = records
        .iter()
        .find_map(|record| match record {
            ContextRecord::Run(run) => Some(run),
            ContextRecord::Result(_) => None,
        })
        .expect("the stream ends with one run record");
    assert!(
        run.status_counts
            .iter()
            .any(|(status, count)| *status == ContextStatus::Unavailable && *count > 0),
        "the run aggregate preserves the unavailable outcome"
    );
}

// ------------------------------------------------- §8C.2 no this-ref #

#[test]
fn no_this_ref_surface_emits_no_requisites_request() {
    let (layout, mapping, _) = pipeline(&wrap(NO_THIS_REF_BODY));
    let records = build_context_records(&layout, &mapping);
    assert!(
        requisites_result(&records).is_none(),
        "without a this-ref surface no current-document requisites request is emitted"
    );
}

// --------------------------------------------- §8C.2 continuation tail #

#[test]
fn proven_continuation_tail_emits_exactly_one_open_series_head() {
    let (layout, mapping, _) = pipeline(&wrap(CONTINUATION_BODY));
    let records = build_context_records(&layout, &mapping);
    let heads: Vec<&ContextResultRecord> = result_records(&records)
        .into_iter()
        .filter(|record| record.request_kind == ContextRequestKind::OpenSeriesHead)
        .collect();
    assert_eq!(
        heads.len(),
        1,
        "exactly one proven continuation tail must emit one open-series-head request"
    );
    assert!(
        matches!(
            heads[0].status,
            ContextStatus::Resolved | ContextStatus::Conflicting
        ),
        "a proven tail resolves or conflicts, never silently drops ({:?})",
        heads[0].status
    );
}

// ------------------------------------------------------- §8C.2 pruning #

#[test]
fn structural_request_kinds_are_never_emitted() {
    for body in [AUTHORIZED_BODY, THIS_REF_ONLY_BODY, CONTINUATION_BODY] {
        let (layout, mapping, _) = pipeline(&wrap(body));
        let records = build_context_records(&layout, &mapping);
        for record in result_records(&records) {
            assert!(
                !matches!(
                    record.request_kind,
                    ContextRequestKind::AncestorPath
                        | ContextRequestKind::AdjacentBlocks
                        | ContextRequestKind::ScopedAlias
                ),
                "structural request kinds are never emitted ({:?})",
                record.request_kind
            );
        }
    }
}

// -------------------------------------------------------- determinism #

#[test]
fn requisites_records_are_deterministic_across_repeated_calls() {
    let (layout, mapping, _) = pipeline(&wrap(AUTHORIZED_BODY));
    let first = build_context_records(&layout, &mapping);
    let second = build_context_records(&layout, &mapping);
    assert_eq!(
        first, second,
        "the sidecar is a pure function of layout + mapping; repeated calls are byte-equal"
    );
}

// ------------------------------------------- §8C.3 closed outcomes (leaf) #

fn type_claim(doc_ref: &str, id: &str, value: &str) -> RequisitesClaim {
    let anchor = SourceAnchor::try_new(
        TextSpan::try_new(0, 1).expect("synthetic anchor span"),
        "block-0".to_string(),
    )
    .expect("document anchor is non-empty");
    RequisitesClaim::try_new(
        id.to_string(),
        doc_ref.to_string(),
        RequisitesField::Type,
        value.to_string(),
        RequisitesSourceKind::DocumentHead,
        anchor,
        "npa_context_records::letterhead-test/v1".to_string(),
        RequisitesExtractionStatus::Observed,
    )
    .expect("a well-formed synthetic claim")
}

#[test]
fn missing_and_conflicting_sidecars_are_never_resolved() {
    let origin = FrameRef::parse("frame-0").expect("synthetic frame ref");
    let evidence = ThisRefGrammarEvidence::new([RequisitesField::Type]);

    let missing = current_document_requisites(None, evidence.clone(), &origin);
    assert_eq!(missing.status, ContextStatus::Unavailable);
    assert_eq!(
        missing.diagnostics,
        vec![ContextDiagnostic::MissingCurrentRequisites]
    );

    let conflicting = CurrentDocumentRequisites::try_new(
        "doc-version-1".to_string(),
        vec![
            type_claim("doc-version-1", "claim-a", "Приказ A"),
            type_claim("doc-version-1", "claim-b", "Приказ B"),
        ],
    )
    .expect("a conflicting sidecar is structurally valid");
    let conflict = current_document_requisites(Some(&conflicting), evidence, &origin);
    assert_eq!(
        conflict.status,
        ContextStatus::Partial,
        "an admitted field that is not agreed never resolves"
    );
    assert_eq!(
        conflict.diagnostics,
        vec![ContextDiagnostic::InheritedFieldConflict]
    );
    assert!(
        conflict.candidates.is_empty(),
        "a conflicting outcome carries no claim candidate"
    );
}
