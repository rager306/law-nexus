//! S03 T02 contract battery (M221-wbslul §8C.1/§8C.2).
//!
//! Executable core of the successor requisites-source and trigger-policy
//! revision of `prd/architecture/npa-analysis-jsonl-contract.md` §8C:
//!
//! * §8C.1 — the `CurrentDocumentRequisites` sidecar is rebuilt
//!   deterministically from the pinned parent (`npa_link::recognize_letterhead`
//!   over the layout block texts), never from an external file or a new
//!   `build_context_records` parameter. A recognized letterhead authorizes the
//!   `Type` this-document reference; a recognized letterhead is absent whenever
//!   the head zone carries no typed anchor.
//! * §8C.2 — deliberate emission: `current_document_requisites` only for a
//!   block carrying a this-ref surface, `open_series_head` only for a proven
//!   continuation tail, `explicit_anchor_lookup` only for a block with a
//!   captured explicit mention. `ancestor_path`/`adjacent_blocks`/`scoped_alias`
//!   are never emitted.
//!
//! Fixtures are inline synthetic WordML documents. Byte expectations are
//! handwritten oracles over the literal block text, never generated by the
//! module under test. Raw decoded corpus text is never logged.

