#[test]
fn document_record_pins_version_and_source_identity() {
    let p = pipeline(&wrap(TYPED_BODY));
    let source_sha256 = p.mapping.envelope().source_sha256.clone();
    let text = render(&wrap(TYPED_BODY));
    let document = lines(&text)
        .into_iter()
        .find(|line| json_string_value(line, "family").as_deref() == Some("document"))
        .expect("document record");
    assert_eq!(
        json_string_value(document, "document_version_ref").as_deref(),
        Some("doc-version-1")
    );
    assert_eq!(
        json_string_value(document, "source_revision").as_deref(),
        Some("rev-1")
    );
    assert_eq!(
        json_string_value(document, "decoder_profile").as_deref(),
        Some("reader_wordml_profile/v1")
    );
    assert_eq!(
        json_string_value(document, "source_sha256").as_deref(),
        Some(source_sha256.as_str())
    );
}

