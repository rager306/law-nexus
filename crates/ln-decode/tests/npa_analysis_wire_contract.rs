//! T04 contract battery (M214-es3jvw S02).
//!
//! Executable core of `prd/architecture/npa-analysis-jsonl-contract.md` §8A:
//! the T02/T03 record streams render into a LF-delimited JSONL envelope
//! (`manifest → policies → records → footer`) with a pinned parent identity,
//! two non-cyclic recomputable seals, a closed completion marker and a
//! count/hash-only fragment channel. `inspect_npa_analysis_wire` is
//! structure-only: it reports families, counts, completion and seal presence.
//!
//! Fixtures are inline non-legal synthetic WordML documents. Byte expectations
//! are handwritten oracles, never generated by the module under test. Raw
//! decoded corpus text is never logged.

use ln_decode::analysis_source_mapping::{SourceIdentity, SourceMapping};
use ln_decode::document_context::DocumentVersionRef;
use ln_decode::npa_analysis_records::{DocumentAnalysis, analyze_document};
use ln_decode::npa_analysis_wire::{
    AnalysisEnvelopeRequest, AnalysisLimits, AnalysisScope, BASIS_COMPLETE, FAMILIES,
    export_npa_analysis, inspect_npa_analysis_wire, recompute_analysis_seals, render_npa_analysis,
};
use ln_decode::reader_contract::{FragmentRef, ReaderRecordIndex};
use ln_decode::reader_projection::{ReaderProjection, build_projection};
use ln_decode::source_package::{Limits, capture};
use sha2::{Digest, Sha256};

fn wrap(body: &str) -> String {
    format!(
        "<w:wordDocument xmlns:w=\"http://schemas.microsoft.com/office/word/2003/wordml\"><w:body>{body}</w:body></w:wordDocument>"
    )
}

struct Pipeline {
    analysis: DocumentAnalysis,
    projection: ReaderProjection,
    index: ReaderRecordIndex,
    mapping: SourceMapping,
}

/// Runs the real pipeline: capture -> projection -> document analysis, with a
/// mapping that pins every substrate fragment.
fn pipeline(xml: &str) -> Pipeline {
    let package = capture(xml.as_bytes(), &Limits::default()).expect("fixture must capture");
    let index = ReaderRecordIndex::new(package.records()).expect("substrate index");
    let projection = build_projection(package.records()).expect("projection must build");
    let identity = SourceIdentity::try_new(
        package.manifest().source.sha256.clone(),
        package.manifest().source.bytes,
        "law-nexus/source-package-model/v1".to_string(),
        package.footer().records_seal_hash.clone(),
        package.footer().manifest_hash.clone(),
    )
    .expect("manifest identity must be well formed");
    let version = DocumentVersionRef::try_new(
        "doc-version-1".to_string(),
        "rev-1".to_string(),
        "reader_wordml_profile/v1".to_string(),
    )
    .expect("version triple must be well formed");
    let mut mapping = SourceMapping::new(identity.clone(), version);
    for text in index.texts() {
        mapping
            .pin_fragment(
                FragmentRef::from(text.id.as_str()),
                text.value.clone(),
                &identity,
            )
            .expect("every substrate fragment must pin");
    }
    let analysis = analyze_document(&projection, &index, &mapping).expect("analysis must build");
    Pipeline {
        analysis,
        projection,
        index,
        mapping,
    }
}

fn render_with(xml: &str, scope: AnalysisScope, limits: AnalysisLimits) -> String {
    let p = pipeline(xml);
    render_npa_analysis(&AnalysisEnvelopeRequest {
        analysis: &p.analysis,
        projection: &p.projection,
        index: &p.index,
        mapping: &p.mapping,
        limits,
        scope,
    })
    .expect("valid analysis must render")
}

fn render(xml: &str) -> String {
    render_with(xml, AnalysisScope::Bounded, AnalysisLimits::default())
}

/// Splits an envelope into its LF-terminated lines.
fn lines(text: &str) -> Vec<&str> {
    assert!(text.ends_with('\n'), "envelope ends with one trailing LF");
    let body = &text[..text.len() - 1];
    body.split('\n').collect()
}

/// Reads one top-level JSON string value out of a canonical compact line.
fn json_string_value(line: &str, key: &str) -> Option<String> {
    let needle = format!("\"{key}\":\"");
    let start = line.find(&needle)? + needle.len();
    let rest = &line[start..];
    let end = rest.find('"')?;
    Some(rest[..end].to_string())
}

/// Reads one top-level JSON unsigned value out of a canonical compact line.
fn json_unsigned_value(line: &str, key: &str) -> Option<u64> {
    let needle = format!("\"{key}\":");
    let start = line.find(&needle)? + needle.len();
    let rest = &line[start..];
    let end = rest
        .find(|ch: char| !ch.is_ascii_digit())
        .unwrap_or(rest.len());
    rest[..end].parse::<u64>().ok()
}

const TYPED_BODY: &str = "<w:p><w:r><w:t>Федеральный закон от 01.01.2020 N 1-ФЗ</w:t></w:r></w:p>";

// ------------------------------------------------------------- layout #

#[test]
fn envelope_is_manifest_policies_records_footer_in_order() {
    let text = render(&wrap(TYPED_BODY));
    let all = lines(&text);
    assert!(all.len() >= 4, "manifest + policies + records + footer");
    assert_eq!(
        json_string_value(all[0], "kind").as_deref(),
        Some("npa_analysis_manifest")
    );
    assert_eq!(
        json_string_value(all[1], "kind").as_deref(),
        Some("npa_analysis_policies")
    );
    let last = all.len() - 1;
    assert_eq!(
        json_string_value(all[last], "kind").as_deref(),
        Some("npa_analysis_footer")
    );
    for (index, line) in all.iter().enumerate().take(last).skip(2) {
        let family = json_string_value(line, "family")
            .unwrap_or_else(|| panic!("interior line {index} has a family"));
        assert!(FAMILIES.contains(&family.as_str()), "family {family:?}");
    }
}

#[test]
fn inspect_reports_families_counts_completion_and_seals() {
    let text = render(&wrap(TYPED_BODY));
    let summary = inspect_npa_analysis_wire(&text).expect("valid envelope must inspect");
    assert_eq!(summary.records, (lines(&text).len() - 3) as u64);
    assert_eq!(
        summary.families.get("document").copied(),
        Some(1),
        "exactly one document record"
    );
    assert!(
        summary.families.get("fragment").copied().unwrap_or(0) >= 1,
        "at least one referenced fragment"
    );
    assert_eq!(summary.completion, "complete");
    assert_eq!(summary.completion_basis, BASIS_COMPLETE);
    assert!(summary.incomplete_reasons.is_empty());
    assert!(summary.records_seal_hash.is_some());
    assert!(summary.manifest_hash.is_some());
}

