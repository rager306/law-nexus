// ---------------------------------------------------------- fragments #

#[test]
fn fragment_records_are_count_hash_only_and_hash_the_substrate() {
    let p = pipeline(&wrap(TYPED_BODY));
    let text = render(&wrap(TYPED_BODY));
    let all = lines(&text);
    let mut seen = 0usize;
    for line in &all {
        if json_string_value(line, "family").as_deref() != Some("fragment") {
            continue;
        }
        seen += 1;
        for forbidden in ["\"text\":", "\"source_utf8\":", "\"decoded_text\":"] {
            assert!(
                !line.contains(forbidden),
                "fragment record must not carry inline decoded text"
            );
        }
        let fragment = json_string_value(line, "fragment_ref").expect("fragment_ref");
        let byte_length = json_unsigned_value(line, "byte_length").expect("byte_length");
        let digest = json_string_value(line, "content_sha256").expect("content_sha256");
        assert_eq!(digest.len(), 64, "sha256 is 64 lowercase hex");
        let substrate = p
            .index
            .text(&fragment)
            .unwrap_or_else(|| panic!("fragment {fragment} is in the substrate"));
        assert_eq!(byte_length, substrate.value.len() as u64);
        let recomputed = hex_lower(&Sha256::digest(substrate.value.as_bytes()));
        assert_eq!(
            digest, recomputed,
            "fragment hash matches its decoded bytes"
        );
    }
    assert!(seen >= 1, "the document references at least one fragment");
}

fn hex_lower(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push_str(&format!("{byte:02x}"));
    }
    out
}

// --------------------------------------------------------------- seals #

#[test]
fn seals_recompute_from_the_emitted_lines() {
    let text = render(&wrap(TYPED_BODY));
    let summary = inspect_npa_analysis_wire(&text).expect("valid envelope");
    let pair = recompute_analysis_seals(&text).expect("seals recompute");
    assert_eq!(
        summary.records_seal_hash.as_deref(),
        Some(pair.records_seal_hash.as_str())
    );
    assert_eq!(
        summary.manifest_hash.as_deref(),
        Some(pair.manifest_hash.as_str())
    );
    assert_ne!(
        pair.records_seal_hash, pair.manifest_hash,
        "the two seals are not the same digest and the chain is non-cyclic"
    );
}

