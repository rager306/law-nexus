//! T02 contract battery (M214-es3jvw S03).
//!
//! Executable core of `prd/architecture/npa-analysis-jsonl-contract.md` §8B
//! (D661/D662/D663): the reader-native context adapter drives the existing
//! document-context index/overlay/worklist from an `AnalysisBlockLayout` and
//! emits a deterministic context record stream. Every context anchor resolves
//! to an exact pinned substrate slice or carries a closed refusal; a non-
//! resolved context status is preserved, never promoted; an index/overlay
//! build failure is a closed, non-dropped outcome.
//!
//! Fixtures are inline synthetic WordML documents. Byte expectations are
//! handwritten oracles over the literal block text, never generated by the
//! module under test. Raw decoded corpus text is never logged.

