fn wrap(body: &str) -> String {
    format!(
        "<w:wordDocument xmlns:w=\"http://schemas.microsoft.com/office/word/2003/wordml\"><w:body>{body}</w:body></w:wordDocument>"
    )
}

/// Runs the real pipeline: capture -> projection -> block layout, with a
/// mapping that pins every substrate fragment.
fn pipeline(xml: &str) -> (AnalysisBlockLayout, SourceMapping) {
    let package = capture(xml.as_bytes(), &Limits::default()).expect("fixture must capture");
    let index = ReaderRecordIndex::new(package.records()).expect("substrate index");
    let projection = build_projection(package.records()).expect("projection must build");
    let identity = SourceIdentity::try_new(
        package.manifest().source.sha256.clone(),
        package.manifest().source.bytes,
        "law-nexus/source-package-model/v1".to_string(),
        package.footer().records_seal_hash.clone(),
        package.footer().manifest_hash.clone(),
    )
    .expect("manifest identity must be well formed");
    let version = DocumentVersionRef::try_new(
        "doc-version-1".to_string(),
        "rev-1".to_string(),
        "reader_wordml_profile/v1".to_string(),
    )
    .expect("version triple must be well formed");
    let mut mapping = SourceMapping::new(identity.clone(), version);
    for text in index.texts() {
        mapping
            .pin_fragment(
                FragmentRef::from(text.id.as_str()),
                text.value.clone(),
                &identity,
            )
            .expect("every substrate fragment must pin");
    }
    let layout =
        build_analysis_block_layout(&projection, &index).expect("analysis layout must build");
    (layout, mapping)
}

/// The same layout with an unpinned mapping (no fragment catalog).
fn unpinned(xml: &str) -> (AnalysisBlockLayout, SourceMapping) {
    let (layout, mapping) = pipeline(xml);
    let identity = mapping.envelope().clone();
    let version = mapping.version().clone();
    (layout, SourceMapping::new(identity, version))
}

fn result_records(records: &[ContextRecord]) -> Vec<&ContextResultRecord> {
    records
        .iter()
        .filter_map(|record| match record {
            ContextRecord::Result(result) => Some(result),
            ContextRecord::Run(_) => None,
        })
        .collect()
}

fn run_record(records: &[ContextRecord]) -> &ln_decode::npa_context_records::ContextRunRecord {
    records
        .iter()
        .find_map(|record| match record {
            ContextRecord::Run(run) => Some(run),
            ContextRecord::Result(_) => None,
        })
        .expect("the stream ends with exactly one run record")
}

fn slice(mapping: &SourceMapping, source: &SourceRef) -> Option<String> {
    let bound = source.as_bound()?;
    let resolved = mapping
        .resolve_fragment_span(&bound.as_fragment_span())
        .ok()?;
    mapping.slice(&resolved).ok().map(|value| value.to_string())
}

// A heading designation frame plus two act-requisites paragraphs: the second
// bare `от ДАТА N` is the documented continuation tail, so the per-frame
// `OpenSeriesHead`/`ExplicitAnchorLookup` requests exercise resolved outcome
// with evidence spanning two analysis blocks.
const CONTEXT_BODY: &str = "<w:p><w:r><w:t>Статья 1. Предмет регулирования</w:t></w:r></w:p>\
     <w:p><w:r><w:t>Федерального закона от 01.01.2020 N 1-ФЗ,</w:t></w:r></w:p>\
     <w:p><w:r><w:t>от 02.02.2021 N 2-ФЗ</w:t></w:r></w:p>";

// A single heading carrying two top-level markers makes the unchanged
// `build_document_structure_index` refuse with `ConflictingRoleEvidence`.
const CONFLICT_BODY: &str = "<w:p><w:r><w:t>РАЗДЕЛ I. Статья 1. Спор</w:t></w:r></w:p>";

// --------------------------------------------------------------- anchors #

#[test]
fn every_anchor_resolves_to_an_exact_fragment_slice_or_a_closed_refusal() {
    let (layout, mapping) = pipeline(&wrap(CONTEXT_BODY));
    let records = build_context_records(&layout, &mapping);
    let results = result_records(&records);
    assert!(
        !results.is_empty(),
        "a framed fixture must emit context result records"
    );

    let mut bound = 0usize;
    for record in &results {
        for anchor in &record.anchors {
            match anchor {
                SourceRef::Bound(_) => {
                    // `resolve_span` already proved slice == the source block slice;
                    // this re-resolves through the seam and requires a real slice.
                    let value = slice(&mapping, anchor).expect("bound anchor must slice");
                    assert!(!value.is_empty(), "anchor slice is non-empty");
                    bound += 1;
                }
                SourceRef::Refused(refusal) => {
                    assert!(
                        !refusal.token().is_empty(),
                        "a refused anchor carries a closed token"
                    );
                }
            }
        }
    }
    assert!(bound > 0, "at least one explicit anchor must resolve");
}

#[test]
fn unpinned_parent_refuses_every_anchor_closed_without_panicking() {
    let (layout, mapping) = unpinned(&wrap(CONTEXT_BODY));
    let records = build_context_records(&layout, &mapping);
    let results = result_records(&records);
    let mut anchors = 0usize;
    for record in &results {
        for anchor in &record.anchors {
            anchors += 1;
            assert_eq!(
                anchor.refusal_token(),
                Some("unknown_fragment"),
                "an unresolved parent is a closed refusal, never a silent success"
            );
        }
    }
    assert!(anchors > 0, "the framed fixture still emits anchors");
}

// ------------------------------------------------------- status fidelity #

#[test]
fn non_resolved_context_statuses_are_preserved_and_never_promoted() {
    let (layout, mapping) = pipeline(&wrap(CONTEXT_BODY));
    let records = build_context_records(&layout, &mapping);
    let results = result_records(&records);

    // No requisites sidecar is supplied, so the current-document requisites
    // request must stay `unavailable` with no anchors.
    let requisites = results
        .iter()
        .find(|record| record.request_kind == ContextRequestKind::CurrentDocumentRequisites)
        .expect("a framed fixture emits one current-document requisites request");
    assert_eq!(requisites.status, ContextStatus::Unavailable);
    assert!(requisites.anchors.is_empty());

    assert!(
        results
            .iter()
            .any(|record| record.status != ContextStatus::Resolved),
        "a non-resolved outcome must survive, never be promoted to resolved"
    );

    let run = run_record(&records);
    assert_eq!(run.requests, results.len());
    assert_eq!(run.resolved + run.non_resolved, run.requests);
    assert!(run.non_resolved > 0, "the run aggregate is honest");
    assert!(
        run.status_counts
            .iter()
            .any(|(status, count)| *status == ContextStatus::Unavailable && *count > 0),
        "per-status counts preserve the unavailable outcome"
    );
}

#[test]
fn view_token_is_covering_for_token_derived_kinds_and_null_for_structural_kinds() {
    let (layout, mapping) = pipeline(&wrap(CONTEXT_BODY));
    let records = build_context_records(&layout, &mapping);
    for record in result_records(&records) {
        match record.request_kind {
            ContextRequestKind::OpenSeriesHead
            | ContextRequestKind::ScopedAlias
            | ContextRequestKind::ExplicitAnchorLookup
            | ContextRequestKind::CurrentDocumentRequisites => {
                assert_eq!(record.view, Some(VIEW_COVERING));
            }
            ContextRequestKind::AncestorPath | ContextRequestKind::AdjacentBlocks => {
                assert_eq!(record.view, None);
            }
        }
    }
}

// --------------------------------------------------------- determinism #

#[test]
fn record_stream_is_deterministic_across_repeated_calls() {
    let (layout, mapping) = pipeline(&wrap(CONTEXT_BODY));
    let first = build_context_records(&layout, &mapping);
    let second = build_context_records(&layout, &mapping);
    assert_eq!(first, second, "context records must be deterministic");
}

#[test]
fn empty_layout_yields_exactly_one_zero_request_run_record() {
    let (_, mapping) = pipeline(&wrap(CONTEXT_BODY));
    let records = build_context_records(&AnalysisBlockLayout::default(), &mapping);
    assert_eq!(records.len(), 1);
    assert_eq!(records[0].kind_token(), KIND_RUN);
    let run = run_record(&records);
    assert_eq!(run.requests, 0);
    assert_eq!(run.resolved, 0);
    assert_eq!(run.non_resolved, 0);
}

// ------------------------------------------------------ closed failure #

#[test]
fn conflicting_structure_is_a_closed_run_record_never_a_panic() {
    let (layout, mapping) = pipeline(&wrap(CONFLICT_BODY));
    let records = build_context_records(&layout, &mapping);
    assert_eq!(
        records.len(),
        1,
        "no result records on a structural refusal"
    );
    assert_eq!(records[0].kind_token(), KIND_RUN);
    let run = run_record(&records);
    assert_eq!(run.requests, 0);
    assert_eq!(
        run.diagnostics,
        vec![ContextDiagnostic::MissingDocumentStructure],
        "the closed structural failure is surfaced, not dropped"
    );
}

